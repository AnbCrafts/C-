using System;
using System.Web.Services;
using System.Web.UI;

namespace DevHelper.Labs
{
    public partial class WebMethodLab : Page
    {
        protected void Page_Load(object sender, EventArgs e)
        {
        }

        /// <summary>
        /// A static WebMethod callable via AJAX / fetch() from the browser.
        /// ASP.NET serializes the return value to JSON automatically!
        /// </summary>
        [WebMethod]
        public static object GetLiveServerData(string query)
        {
            return new
            {
                Status = "Success",
                ServerTime = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss"),
                ReceivedQuery = query,
                MachineName = Environment.MachineName,
                Framework = ".NET Framework 4.7.2 Web Forms",
                Message = "This JSON was generated by a C# WebMethod in ASP.NET Web Forms without rendering any HTML page!"
            };
        }
    }
}
